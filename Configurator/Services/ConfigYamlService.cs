using System.Text;
using System.Text.RegularExpressions;
using Configurator.Data.Model;
using YamlDotNet.Serialization;
using YamlDotNet.Serialization.NamingConventions;

namespace Configurator.Services;

/// <summary>Turns AgentSettings into the agent's config.yml and back; validates the values like the agent does.</summary>
public class ConfigYamlService
{
    private static readonly ISerializer Serializer = new SerializerBuilder()
        .WithNamingConvention(UnderscoredNamingConvention.Instance)
        .WithQuotingNecessaryStrings()
        .DisableAliases()
        .Build();

    private static readonly IDeserializer Deserializer = new DeserializerBuilder()
        .WithNamingConvention(UnderscoredNamingConvention.Instance)
        .IgnoreUnmatchedProperties()
        .Build();

    public string ToYaml(AgentSettings settings, string? description)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# SshSecMonitorer agent configuration");
        sb.AppendLine($"# Generated by the Configurator on {DateTime.UtcNow:yyyy-MM-dd HH:mm} UTC");
        if (!string.IsNullOrWhiteSpace(description))
            sb.AppendLine($"# {description.ReplaceLineEndings(" ")}");
        sb.AppendLine("# All intervals and retentions are in seconds.");
        sb.AppendLine();
        sb.Append(Serializer.Serialize(settings));
        return sb.ToString();
    }

    /// <summary>Reads a config.yml (e.g. pasted from an existing agent). Unknown keys are ignored.</summary>
    public AgentSettings FromYaml(string yaml) => Deserializer.Deserialize<AgentSettings>(yaml) ?? new AgentSettings();

    /// <summary>Same rules as ConfigLoader._validate in the agent.</summary>
    public List<string> Validate(AgentSettings s)
    {
        var errors = new List<string>();
        if (string.IsNullOrWhiteSpace(s.Agent.Name))
            errors.Add("agent.name darf nicht leer sein.");
        if (string.IsNullOrWhiteSpace(s.Agent.OutputFile) || !s.Agent.OutputFile.StartsWith('/'))
            errors.Add("agent.output_file muss ein absoluter Pfad sein.");
        foreach (var (key, value) in new[]
                 {
                     ("agent.write_interval", s.Agent.WriteInterval),
                     ("host.interval", s.Host.Interval),
                     ("docker.interval", s.Docker.Interval),
                     ("docker.logs.interval", s.Docker.Logs.Interval)
                 })
        {
            if (value < 1)
                errors.Add($"{key} muss mindestens 1 sein.");
        }
        if (s.Host.HistoryRetention < 0 || s.Docker.HistoryRetention < 0)
            errors.Add("history_retention darf nicht negativ sein.");
        if (!Regex.IsMatch(s.Agent.OutputFileMode ?? "", "^0?[0-7]{3}$"))
            errors.Add("agent.output_file_mode muss eine Oktalzahl wie 0644 sein.");
        foreach (var (key, pattern) in new[]
                 {
                     ("docker.logs.error_pattern", s.Docker.Logs.ErrorPattern),
                     ("docker.logs.warning_pattern", s.Docker.Logs.WarningPattern)
                 })
        {
            try
            {
                // inline flags like (?i) are valid in .NET and Python
                _ = new Regex(pattern ?? "");
            }
            catch (ArgumentException ex)
            {
                errors.Add($"{key} ist kein gültiger regulärer Ausdruck: {ex.Message}");
            }
        }
        return errors;
    }
}
